#!/usr/bin/env bash
# Qwen3-VL-4B EB-prompt baseline on EB-Navigation TEST with Qwen's official FP8 checkpoint (rerun of eb_official_r1,
# whose 4-bit AWQ weights may understate the baseline; see docs/experiment_inventory.md, 2026-11-02).
# Same prompt, schema and decoding as eb_official_r1; only the weights change. Server settings, found by test
# starts on 2026-11-02: DeepGEMM off (its kernels need nvcc, which this machine lacks; vLLM then uses its CUTLASS
# FP8 block-scaled kernel), 1 GB of the 6 GB checkpoint offloaded to CPU so that a bf16 KV cache for the full
# 8192-token window fits (8,928 tokens), eager mode. Without the offload only 0.15 GiB is left for the KV cache.
# Waits for the robotics-qwen25dev unit to finish first.
#   bash scripts/run_qwen3_fp8_eb.sh
set -uo pipefail
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
M=models/Qwen3-VL-4B-Instruct-FP8
while systemctl --user is-active --quiet robotics-qwen25dev; do sleep 30; done
for _ in $(seq 1 360); do  # the download must be complete: no partial file and the index present
  [ -f "$M/model.safetensors.index.json" ] && [ -z "$(find "$M" -name '*.part')" ] && break; sleep 10
done
Q=queues/qwen3_fp8_eb_test.txt
cat > "$Q" <<EOF
# generated by scripts/run_qwen3_fp8_eb.sh: Qwen3-VL-4B EB prompt, official FP8 weights, EB TEST (300 episodes)
$M | 8192 | 0.84 | /home/ht/miniforge3/envs/embnav_thor/bin/python -m embagent.eb.nav_runner --planner eb --model Qwen3-VL-4B-Instruct-FP8 --exp eb_official_r1 --workers 1
EOF
args="--mm-processor-cache-gb 0 --enforce-eager --cpu-offload-gb 1"
echo "$(date '+%F %T') server: VLLM_USE_DEEP_GEMM=0 $args" >> logs/qwen3_fp8_eb_server.txt
VLLM_USE_DEEP_GEMM=0 VLLM_SERVER_ARGS="$args" LOG_PREFIX=q3fp8 bash scripts/run_queue.sh "$Q" >> logs/queue_qwen3_fp8_eb.log 2>&1
rc=$?
echo "$(date '+%F %T') exit $rc" >> logs/qwen3_fp8_eb_server.txt
exit "$rc"
