"""Copy every figure of the thesis into figures_review/ for reviewing, named by its figure number.

  python3 thesis/export_figures_for_review.py
    -> figures_review/Fig_<n>_<file>.png   the figure file itself, 200 dpi
       figures_review/Page_<p>_Fig_<n>.png the PDF page on which the figure appears, as the reader sees it
       figures_review/README.md            figure number, page, source file, caption
"""
import glob
import os
import re
import shutil
import subprocess

T = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(T, "figures_review")
TEX = os.path.expanduser("~/miniforge3/envs/tex/bin/tectonic")

# compile once with intermediates to read the figure numbers and pages from the .aux file
tmp = "/tmp/thesis_review_build"
os.makedirs(tmp, exist_ok=True)
subprocess.run([TEX, "-X", "compile", os.path.join(T, "main.tex"), "--keep-intermediates", "--outdir", tmp],
               cwd=T, capture_output=True, check=True)
aux = open(os.path.join(tmp, "main.aux")).read()
ref = {m.group(1): (m.group(2), m.group(3)) for m in
       re.finditer(r"\\newlabel\{(fig:[^}]+)\}\{\{([^}]*)\}\{([^}]*)\}", aux)}

# every figure environment: its graphics file, label, and short caption
figs = []
for f in sorted(glob.glob(os.path.join(T, "chapters", "*.tex")) + glob.glob(os.path.join(T, "chapters", "generated", "*.tex"))):
    s = open(f).read()
    for env in re.finditer(r"\\begin\{figure\}.*?\\end\{figure\}", s, re.S):
        e = env.group(0)
        g = re.search(r"\\includegraphics(?:\[[^]]*\])?\{([^}]+)\}", e)
        lab = re.search(r"\\label\{(fig:[^}]+)\}", e)
        cap = re.search(r"\\caption(?:\[([^]]*)\])?\{(.*)", e, re.S)
        if g and lab:
            short = cap.group(1) if cap and cap.group(1) else (cap.group(2).split(".")[0] if cap else "")
            figs.append((lab.group(1), g.group(1), re.sub(r"\\[a-zA-Z]+|[{}$\\~]", "", short.replace("\\ours", "S2M")).strip()))

if os.path.isdir(OUT):
    shutil.rmtree(OUT)
os.makedirs(OUT)
pdf = os.path.join(T, "main.pdf")
rows = []
for lab, path, short in sorted(figs, key=lambda x: [int(p) if p.isdigit() else p for p in re.split(r"[.]", ref.get(x[0], ("99", ""))[0])]):
    num, page = ref.get(lab, ("?", "?"))
    src = os.path.join(T, path if path.endswith((".pdf", ".png")) else path + ".pdf")
    base = os.path.splitext(os.path.basename(src))[0]
    name = f"Fig_{num.replace('.', '-')}_{base}"
    if src.endswith(".pdf"):
        subprocess.run(["pdftoppm", "-r", "200", "-png", "-singlefile", src, os.path.join(OUT, name)], check=True)
    else:
        shutil.copy(src, os.path.join(OUT, name + ".png"))
    # the page as it appears in the thesis (Arabic page numbers start at Chapter 1)
    rows.append((num, page, os.path.relpath(src, T), short, name))

# physical page of each Arabic page number: find the first page whose footer is that number
info = subprocess.run(["pdfinfo", pdf], capture_output=True, text=True).stdout
npages = int(re.search(r"Pages:\s+(\d+)", info).group(1))
footer = {}
for p in range(1, npages + 1):
    txt = subprocess.run(["pdftotext", "-f", str(p), "-l", str(p), "-layout", pdf, "-"], capture_output=True, text=True).stdout
    last = [l.strip() for l in txt.splitlines() if l.strip()]
    if last and last[-1].isdigit():
        footer.setdefault(last[-1], p)
for num, page, _, _, name in rows:
    if page in footer:
        subprocess.run(["pdftoppm", "-r", "110", "-png", "-singlefile", "-f", str(footer[page]), "-l", str(footer[page]), pdf,
                        os.path.join(OUT, f"Page_{page}_Fig_{num.replace('.', '-')}")], check=True)

with open(os.path.join(OUT, "README.md"), "w") as f:
    f.write("# Thesis figures for review\n\n"
            "Generated by `export_figures_for_review.py` from `main.pdf`; regenerate after every change.\n"
            "`Fig_*.png`: the figure alone (200 dpi). `Page_*.png`: the thesis page on which it appears.\n\n"
            "| Figure | Page | Image | Source file | Title |\n|---|---|---|---|---|\n")
    for num, page, src, short, name in rows:
        f.write(f"| {num} | {page} | `{name}.png` | `{src}` | {short} |\n")
print(f"{len(rows)} figures -> {OUT}")
for r in rows:
    print(f"  Fig {r[0]:>4}  p.{r[1]:>3}  {r[4]}.png  ({r[3]})")
